#!/usr/bin/env python3
"""Generates iOS .strings and Android strings.xml from i18n/translations.txt (single source of truth).
Run from the repo root:  python3 i18n/generate.py
iOS uses the English text as the lookup key (SwiftUI literals); Android uses the id."""
import os, re, sys

LANGS = ["en", "sv", "es", "fr", "de", "pt", "it", "ar", "tr", "ru", "zh", "ja"]
IOS_DIR = {"zh": "zh-Hans"}                       # lproj folder names
AND_DIR = {"en": "values", "zh": "values-zh"}     # res folder names (default: values-<code>)
LOCALES_CONFIG = {"zh": "zh-CN"}                  # tags in locales_config.xml
root = os.path.dirname(os.path.abspath(__file__))
repo = os.path.dirname(root)

def rows(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line and not line.startswith("#"): out.append(line.split("|"))
    return out

def ios_str(s):  return s.replace("\\", "\\\\").replace('"', '\\"').replace("{n}", "%lld")
def and_str(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"').replace("{n}", "%1$d")
    return "\\@" + s[1:] if s.startswith("@") else s

tr = rows(os.path.join(root, "translations.txt"))
for r in tr:
    if len(r) != 1 + len(LANGS): sys.exit(f"bad row (expected {1+len(LANGS)} fields, got {len(r)}): {r[0]}")
    for i, v in enumerate(r[1:]):
        if ("{n}" in r[1]) != ("{n}" in v): sys.exit(f"placeholder mismatch in {r[0]} [{LANGS[i]}]")

ios_res = os.path.join(repo, "NearsendChatiOS/Sources/Resources")
and_res = os.path.join(repo, "NearsendChatAndroid/app/src/main/res")
for li, lang in enumerate(LANGS):
    d = os.path.join(ios_res, IOS_DIR.get(lang, lang) + ".lproj"); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("/* Generated by i18n/generate.py - do not edit. */\n")
        for r in tr: f.write(f'"{ios_str(r[1])}" = "{ios_str(r[1 + li])}";\n')
    d = os.path.join(and_res, AND_DIR.get(lang, f"values-{lang}")); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by i18n/generate.py - do not edit. -->\n<resources>\n')
        if lang == "en": f.write('    <string name="app_name" translatable="false">Nearsend Chat</string>\n')
        for r in tr: f.write(f'    <string name="{r[0]}">{and_str(r[1 + li])}</string>\n')
        f.write("</resources>\n")

for r in rows(os.path.join(root, "plist.txt")):
    lang = r[0]
    d = os.path.join(ios_res, IOS_DIR.get(lang, lang) + ".lproj"); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "InfoPlist.strings"), "w", encoding="utf-8") as f:
        f.write(f'"NSBluetoothAlwaysUsageDescription" = "{ios_str(r[1])}";\n"NSLocalNetworkUsageDescription" = "{ios_str(r[2])}";\n')

os.makedirs(os.path.join(and_res, "xml"), exist_ok=True)
with open(os.path.join(and_res, "xml/locales_config.xml"), "w", encoding="utf-8") as f:
    f.write('<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n')
    for lang in LANGS: f.write(f'    <locale android:name="{LOCALES_CONFIG.get(lang, lang)}" />\n')
    f.write("</locale-config>\n")
print(f"generated {len(tr)} strings x {len(LANGS)} languages")
