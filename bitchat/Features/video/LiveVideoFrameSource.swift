import AVFoundation
import BitLogger
import CoreVideo
import Foundation

/// Where a live video sender gets its pictures and (optional) audio: the
/// camera + microphone, or a synthetic test card + tone.
///
/// Timestamps are microseconds on one clock that starts at 0 when `start()`
/// begins, shared by video and audio so the sender can interleave them.
/// `onAudioFrames` delivers consecutive raw AAC-LC frames (16 kHz mono, no
/// ADTS); its timestamp is the first frame's, each following frame is
/// `PTTAudioFormat.frameDuration` later. Callbacks run on the source's
/// serial queues; set them before `start()`.
protocol LiveVideoFrameSource: AnyObject {
    var onPixelBuffer: ((CVPixelBuffer, Int64) -> Void)? { get set }
    var onAudioFrames: (([Data], Int64) -> Void)? { get set }
    /// Muted audio keeps flowing as encoded silence, so viewers' audio clock
    /// and the recording's timeline stay continuous.
    var isMuted: Bool { get set }
    @MainActor func start() async throws
    @MainActor func stop()
}

/// Deterministic moving test card (color bars, a bouncing box, a frame
/// counter in digits and binary) plus a 440 Hz tone, for the simulator (which
/// has no camera) and automated tests, so nothing ever captures a real room.
///
/// `@unchecked Sendable`: generator state is confined to `queue`; `isMuted`
/// is lock-protected.
final class LiveVideoSyntheticSource: LiveVideoFrameSource, @unchecked Sendable {
    let width: Int
    let height: Int
    let fps: Int
    let audioEnabled: Bool
    let toneHz: Double

    var onPixelBuffer: ((CVPixelBuffer, Int64) -> Void)?
    var onAudioFrames: (([Data], Int64) -> Void)?

    var isMuted: Bool {
        get { muteLock.withLock { muted } }
        set { muteLock.withLock { muted = newValue } }
    }

    private let queue = DispatchQueue(label: "chat.bitchat.video.synthetic", qos: .userInitiated)
    private let muteLock = NSLock()
    private var muted = false

    // Queue-confined state.
    private var videoTimer: DispatchSourceTimer?
    private var audioTimer: DispatchSourceTimer?
    private var startUptimeNs: UInt64 = 0
    private var frameIndex = 0
    private var audioEncoder: PTTFrameEncoder?
    private var samplesGenerated: Int64 = 0
    private var aacFramesEmitted: Int64 = 0
    private var pool: CVPixelBufferPool?
    private lazy var background: [UInt32] = makeBackground()

    init(width: Int = 480, height: Int = 640, fps: Int = 15, audioEnabled: Bool = true, toneHz: Double = 440) {
        self.width = max(16, width & ~1)
        self.height = max(16, height & ~1)
        self.fps = min(max(fps, 1), 60)
        self.audioEnabled = audioEnabled
        self.toneHz = toneHz
    }

    deinit {
        videoTimer?.cancel()
        audioTimer?.cancel()
    }

    func start() async throws {
        queue.sync {
            guard videoTimer == nil else { return }
            startUptimeNs = DispatchTime.now().uptimeNanoseconds
            frameIndex = 0
            samplesGenerated = 0
            aacFramesEmitted = 0
            audioEncoder = audioEnabled ? PTTFrameEncoder() : nil
            if audioEnabled, audioEncoder == nil {
                SecureLogger.error("Live video: synthetic tone encoder unavailable", category: .session)
            }

            let video = DispatchSource.makeTimerSource(queue: queue)
            video.schedule(deadline: .now(), repeating: .nanoseconds(1_000_000_000 / fps), leeway: .milliseconds(2))
            video.setEventHandler { [weak self] in self?.emitVideoFrame() }
            videoTimer = video
            video.resume()

            if audioEncoder != nil {
                // Generated by elapsed sample count, so timer jitter never
                // stretches or squeezes the tone's timeline.
                let audio = DispatchSource.makeTimerSource(queue: queue)
                audio.schedule(deadline: .now(), repeating: .milliseconds(32), leeway: .milliseconds(4))
                audio.setEventHandler { [weak self] in self?.emitAudio() }
                audioTimer = audio
                audio.resume()
            }
        }
    }

    func stop() {
        queue.sync {
            videoTimer?.cancel()
            audioTimer?.cancel()
            videoTimer = nil
            audioTimer = nil
            audioEncoder = nil
        }
    }

    // MARK: - Generators (also used directly by tests)

    /// Renders test-card frame `index` as a BGRA pixel buffer.
    func makeFrame(index: Int) -> CVPixelBuffer? {
        if pool == nil {
            let attributes: [CFString: Any] = [
                kCVPixelBufferPixelFormatTypeKey: kCVPixelFormatType_32BGRA,
                kCVPixelBufferWidthKey: width,
                kCVPixelBufferHeightKey: height,
                kCVPixelBufferIOSurfacePropertiesKey: [String: Any]()
            ]
            CVPixelBufferPoolCreate(kCFAllocatorDefault, nil, attributes as CFDictionary, &pool)
        }
        var created: CVPixelBuffer?
        if let pool {
            CVPixelBufferPoolCreatePixelBuffer(kCFAllocatorDefault, pool, &created)
        }
        guard let buffer = created else { return nil }

        CVPixelBufferLockBaseAddress(buffer, [])
        defer { CVPixelBufferUnlockBaseAddress(buffer, []) }
        guard let base = CVPixelBufferGetBaseAddress(buffer) else { return nil }
        let rowPixels = CVPixelBufferGetBytesPerRow(buffer) / 4
        let pixels = base.bindMemory(to: UInt32.self, capacity: rowPixels * height)

        background.withUnsafeBufferPointer { source in
            guard let sourceBase = source.baseAddress else { return }
            for row in 0..<height {
                (pixels + row * rowPixels).update(from: sourceBase + row * width, count: width)
            }
        }

        // A box bouncing diagonally, its color cycling, so motion and
        // freezes are obvious at a glance.
        let box = max(8, width / 4)
        let left = Self.bounce(index * 5, range: width - box)
        let top = Self.bounce(index * 3, range: height - box)
        let boxColor = Self.palette[(index / 8) % Self.palette.count]
        fill(pixels, rowPixels, x: left, y: top, w: box, h: box, color: Self.white)
        fill(pixels, rowPixels, x: left + 3, y: top + 3, w: box - 6, h: box - 6, color: boxColor)

        // Binary frame counter strip across the top (12 bits).
        let cell = max(1, width / 12)
        for bit in 0..<12 {
            let on = (index >> bit) & 1 == 1
            fill(pixels, rowPixels, x: bit * cell, y: 0, w: cell, h: max(4, height / 64), color: on ? Self.white : Self.black)
        }

        // Decimal frame counter, bottom-left, on a dark plate.
        let digits = Array(String(index))
        let scale = max(2, width / 60)
        let plateHeight = 7 * scale
        fill(pixels, rowPixels, x: 0, y: height - plateHeight, w: (digits.count * 4 + 1) * scale, h: plateHeight, color: Self.black)
        for (position, character) in digits.enumerated() {
            guard let glyph = Self.glyphs[character] else { continue }
            for (row, bits) in glyph.enumerated() {
                for column in 0..<3 where bits & (0b100 >> column) != 0 {
                    fill(
                        pixels, rowPixels,
                        x: (position * 4 + 1 + column) * scale,
                        y: height - plateHeight + (row + 1) * scale,
                        w: scale, h: scale,
                        color: Self.white
                    )
                }
            }
        }
        return buffer
    }

    /// `frameCount` samples of the tone (or silence) at 16 kHz mono, phase-
    /// continuous from sample `startSample`.
    func makeToneBuffer(startSample: Int64, frameCount: AVAudioFrameCount, silent: Bool = false) -> AVAudioPCMBuffer? {
        guard let format = PTTAudioFormat.pcmFormat,
              let buffer = AVAudioPCMBuffer(pcmFormat: format, frameCapacity: frameCount),
              let channel = buffer.floatChannelData?[0]
        else { return nil }
        buffer.frameLength = frameCount
        let step = 2 * Double.pi * toneHz / PTTAudioFormat.sampleRate
        for index in 0..<Int(frameCount) {
            channel[index] = silent ? 0 : Float(0.25 * sin(step * Double(startSample + Int64(index))))
        }
        return buffer
    }

    // MARK: - Queue

    private var elapsedUs: Int64 {
        Int64((DispatchTime.now().uptimeNanoseconds - startUptimeNs) / 1_000)
    }

    private func emitVideoFrame() {
        let ptsUs = elapsedUs
        guard let frame = makeFrame(index: frameIndex) else { return }
        frameIndex += 1
        onPixelBuffer?(frame, ptsUs)
    }

    private func emitAudio() {
        guard let encoder = audioEncoder else { return }
        let frameSamples = Int64(PTTAudioFormat.samplesPerFrame)
        let dueSamples = elapsedUs * Int64(PTTAudioFormat.sampleRate) / 1_000_000
        var frames: [Data] = []
        while samplesGenerated + frameSamples <= dueSamples {
            guard let pcm = makeToneBuffer(
                startSample: samplesGenerated,
                frameCount: PTTAudioFormat.samplesPerFrame,
                silent: isMuted
            ) else { return }
            samplesGenerated += frameSamples
            frames.append(contentsOf: encoder.encode(pcm))
        }
        guard !frames.isEmpty else { return }
        let ptsUs = aacFramesEmitted * frameSamples * 1_000_000 / Int64(PTTAudioFormat.sampleRate)
        aacFramesEmitted += Int64(frames.count)
        onAudioFrames?(frames, ptsUs)
    }

    // MARK: - Drawing

    private static let white: UInt32 = bgra(235, 235, 235)
    private static let black: UInt32 = bgra(16, 16, 16)
    /// SMPTE-ish bars: white, yellow, cyan, green, magenta, red, blue, black.
    private static let bars: [UInt32] = [
        bgra(192, 192, 192), bgra(192, 192, 0), bgra(0, 192, 192), bgra(0, 192, 0),
        bgra(192, 0, 192), bgra(192, 0, 0), bgra(0, 0, 192), bgra(16, 16, 16)
    ]
    private static let palette: [UInt32] = [
        bgra(255, 64, 64), bgra(64, 255, 64), bgra(64, 64, 255), bgra(255, 200, 0)
    ]
    /// 3×5 digit glyphs, one row per entry, MSB = leftmost column.
    private static let glyphs: [Character: [UInt8]] = [
        "0": [0b111, 0b101, 0b101, 0b101, 0b111], "1": [0b010, 0b110, 0b010, 0b010, 0b111],
        "2": [0b111, 0b001, 0b111, 0b100, 0b111], "3": [0b111, 0b001, 0b111, 0b001, 0b111],
        "4": [0b101, 0b101, 0b111, 0b001, 0b001], "5": [0b111, 0b100, 0b111, 0b001, 0b111],
        "6": [0b111, 0b100, 0b111, 0b101, 0b111], "7": [0b111, 0b001, 0b010, 0b010, 0b010],
        "8": [0b111, 0b101, 0b111, 0b101, 0b111], "9": [0b111, 0b101, 0b111, 0b001, 0b111]
    ]

    private static func bgra(_ red: UInt32, _ green: UInt32, _ blue: UInt32) -> UInt32 {
        // Little-endian 32BGRA: B in the low byte, A in the high byte.
        blue | (green << 8) | (red << 16) | (0xFF << 24)
    }

    private static func bounce(_ value: Int, range: Int) -> Int {
        guard range > 0 else { return 0 }
        let period = range * 2
        let phase = value % period
        return phase <= range ? phase : period - phase
    }

    /// Color bars over the top two thirds, a grey ramp below.
    private func makeBackground() -> [UInt32] {
        var pixels = [UInt32](repeating: 0, count: width * height)
        let barsHeight = height * 2 / 3
        for row in 0..<height {
            for column in 0..<width {
                if row < barsHeight {
                    pixels[row * width + column] = Self.bars[column * Self.bars.count / width]
                } else {
                    let level = UInt32(16 + column * 219 / max(1, width - 1))
                    pixels[row * width + column] = Self.bgra(level, level, level)
                }
            }
        }
        return pixels
    }

    private func fill(_ pixels: UnsafeMutablePointer<UInt32>, _ rowPixels: Int, x: Int, y: Int, w: Int, h: Int, color: UInt32) {
        let x0 = max(0, x)
        let y0 = max(0, y)
        let x1 = min(width, x + w)
        let y1 = min(height, y + h)
        guard x1 > x0, y1 > y0 else { return }
        for row in y0..<y1 {
            (pixels + row * rowPixels + x0).update(repeating: color, count: x1 - x0)
        }
    }
}
